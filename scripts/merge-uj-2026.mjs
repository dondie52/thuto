function main() {
  const existing = JSON.parse(fs.readFileSync(progPath, "utf8"));

  const byId = new Map();
  existing.forEach((p, idx) => {
    if (p && p.id) byId.set(p.id, idx);
  });

  let added = 0;
  let updated = 0;

  for (const raw of programmes) {
    const id = raw.id && raw.id.startsWith("uj-") ? raw.id : `uj-${slugify(raw.id || raw.name)}`;
    const record = { ...raw, id };

    if (byId.has(id)) {
      const idx = byId.get(id);
      existing[idx] = { ...existing[idx], ...record };
      updated++;
    } else {
      existing.push(record);
      byId.set(id, existing.length - 1);
      added++;
    }
  }

  fs.writeFileSync(progPath, `${JSON.stringify(existing, null, 2)}
`);
  console.error(`UJ 2026 merge: added ${added} new programmes; updated ${updated} existing programmes (total UJ records processed: ${programmes.length}).`);
}

main();
