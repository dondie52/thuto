/**
 * Enrich the University of the Witwatersrand (Wits) 2027-intake undergraduate programme
 * catalogue in public/data/programmes.json using the official Wits undergraduate prospectus
 * summary supplied by the user.
 *
 * Patches the 23 existing wits-* stub entries (id preserved) with real descriptions, careers,
 * fees, durations, and deadlines, and adds the remaining programmes from the prospectus that
 * don't yet have an entry.
 *
 * NOTE on scale: `minPoints`/`subjectRequirements` are always expressed on Thuto's Botswana
 * BGCSE 48-point best-six scale (see src/lib/gradingSystems.js `requiredIndexFromMinPoints`),
 * and subjectRequirements values must be BGCSE letter grades (src/lib/admissions.js
 * `rowsToRequirementGrades`). Wits' APS (best-seven, NSC achievement levels) is a different
 * scale with no established conversion in this codebase, so those two fields are left null/{}
 * here — matching every other South African programme already in programmes.json. Raw
 * APS/NBT/subject-level requirements are kept as plain text in `requirements`.
 *
 * Usage: node scripts/merge-wits-2027.mjs
 */
