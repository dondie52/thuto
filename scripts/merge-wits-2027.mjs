function main() {
  const existing = JSON.parse(fs.readFileSync(progPath, "utf8"));
  const byId = new Map(existing.map((prog) => [prog.id, prog]));
  let added = 0;
  let updated = 0;
  for (const prog of programmes) {
    if (byId.has(prog.id)) {
      Object.assign(byId.get(prog.id), prog);
      updated++;
    } else {
      existing.push(prog);
      byId.set(prog.id, prog);
      added++;
    }
  }
  fs.writeFileSync(progPath, `${JSON.stringify(existing, null, 2)}\n`);
  console.error(`Wits merge: programmes added ${added}, updated ${updated}.`);
}

main();
