function slugify(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function feesFromRange(rangeText) {
  if (!rangeText) return undefined;
  const nums = rangeText.replace(/[R,\s]/g, "").match(/\d+(?:\.\d+)?/g);
  if (!nums || !nums.length) return undefined;
  const low = Number(nums[0]);
  return {
    domestic: low,
    currency: "ZAR",
    per: "year",
    note: `2026 first-year approximate fee: R${rangeText.replace(/^R/, "")} (South African citizens; ~5%+ annual increase expected for 2027). Verify with Wits.`,
  };
}

function p({ id, name, field, faculty, duration, durationYears, requirements, careers, description, fees, deadline, campus }) {
  const out = {
    id: `wits-${id}`,
    name,
    field,
    university: UNIVERSITY_NAME,
    universityShort: UNIVERSITY_SHORT,
    country: "za",
    minPoints: null,
    subjectRequirements: {},
    duration,
    durationYears,
    description,
    officialUrl: OFFICIAL_URL,
    applyUrl: APPLY_URL,
    modules: [],
    careers,
    applicationDeadline: deadline || "2026-09-30",
    minPointsSource: null,
    minPointsTier: "manual",
    minPointsScaleVersion: 2,
    profileCompleteness: "partial",
    sponsorshipTier: "standard",
    qualification: "Bachelor's degree",
    campus: campus || "Braamfontein",
    faculty,
    requirements,
  };
  if (fees) out.fees = fees;
  return out;
}

